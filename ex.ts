    
    function multiplicar(num1: number, num2: number): number {
        return num1 * num2;
    }
    

    function saudar(nome: string): string {
        return "Olá " + nome;
    }
    
    
    const resultadoMultiplicacao = multiplicar(5, 10);
    console.log(resultadoMultiplicacao); // Saída: 50
    
    const saudacaoPessoa = saudar("João");
    console.log(saudacaoPessoa); // Saída: Olá João